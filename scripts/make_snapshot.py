"""Bundle the docs and source into one Markdown file for sharing or review.

    python scripts/make_snapshot.py            # -> project_snapshot.md (git-ignored)
    python scripts/make_snapshot.py --no-code  # docs and results only

Order: README, status, architecture, LLM setup, checklist, plan, results,
then every source file. Data files and model weights are summarized, not
included.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ["README.md", "docs/STATUS.md", "docs/ARCHITECTURE.md", "docs/LLM_SETUP.md",
        "docs/VERIFICATION_CHECKLIST.md", "docs/ENGINEERING_PLAN.md", "results/REPORT.md",
        "LICENSES.md", "Makefile", "requirements.txt", ".env.example"]
CODE_DIRS = ["taskflow", "scripts", "tests"]


def tracked_files() -> list[str]:
    try:
        out = subprocess.check_output(["git", "ls-files"], cwd=ROOT, text=True)
        return out.split()
    except Exception:
        return [str(p.relative_to(ROOT)) for p in ROOT.rglob("*") if p.is_file()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "project_snapshot.md")
    ap.add_argument("--no-code", action="store_true")
    a = ap.parse_args()
    files = tracked_files()
    parts = ["# TaskFlow-Travel project snapshot", "",
             "Generated by scripts/make_snapshot.py. Start with README and docs/STATUS.md.", "",
             "## File tree", "", "```", *sorted(files), "```", ""]
    for f in DOCS:
        p = ROOT / f
        if p.exists():
            lang = "" if f.endswith(".md") else "text"
            body = p.read_text()
            parts += [f"## {f}", ""] + ([body] if f.endswith(".md") else [f"```{lang}", body, "```"]) + [""]
    manifest = ROOT / "data/tasks/v0/manifest.json"
    if manifest.exists():
        parts += ["## data/tasks/v0/manifest.json", "", "```json", manifest.read_text(), "```", ""]
    log = ROOT / "models/training_log.json"
    if log.exists():
        parts += ["## models/training_log.json (summary)", "", "```json",
                  json.dumps(json.loads(log.read_text())["runs"].get("0", {}), indent=1), "```", ""]
    if not a.no_code:
        for f in sorted(files):
            if f.endswith(".py") and f.split("/")[0] in CODE_DIRS:
                parts += [f"## {f}", "", "```python", (ROOT / f).read_text(), "```", ""]
    a.out.write_text("\n".join(parts))
    print(f"wrote {a.out} ({a.out.stat().st_size / 1024:.0f} KB)", file=sys.stderr)


if __name__ == "__main__":
    main()
